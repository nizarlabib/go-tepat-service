func seedRoles(permissions []*entity.Permission, db *gorm.DB) {
	logger.Info("Seeding roles")

	calc := func(indices []int) string {
		perms := permission.New()
		for _, idx := range indices {
			if idx < 1 || idx > len(permissions) {
				log.Println(len(permissions))
				continue
			}
			p := permissions[idx-1]
			perms.Grant(p.BitIndex)

			if p.BitIndex == permissionindex.Admin {
				perms.Grant(permissionindex.User)
			}
		}
		return perms.String()
	}

	// posM := map[int]int{}
	// getPosByPermIdx := func(permIdx int) int {
	// 	for idx, p := range permissions {
	// 		if pos, ok := posM[permIdx]; ok {
	// 			return pos
	// 		}
	// 		if p.BitIndex == permIdx {
	// 			posM[permIdx] = idx + 1
	// 			return idx + 1
	// 		}
	// 	}
	// 	return -1
	// }

	superAdminPerms := calc([]int{1, 2, 3, 4, 5, 6, 7})
	adminPerms := calc([]int{2})
	userPerms := calc([]int{3})

	fmt.Println("Seeding roles...")
	roles := []*entity.Role{
		{ID: rbac.UUIDPad(1), Name: "Super Admin", Description: "generated by system", PermissionMask: superAdminPerms, IsDefault: true},
		{ID: rbac.UUIDPad(2), Name: "Admin", Description: "generated by system", PermissionMask: adminPerms, IsDefault: true},
		{ID: rbac.UUIDPad(3), Name: "User", Description: "generated by system", PermissionMask: userPerms, IsDefault: true},
	}

	err := db.Clauses(clause.OnConflict{
		Columns:   []clause.Column{{Name: "uuid"}},
		DoUpdates: clause.AssignmentColumns([]string{"name", "permission_mask", "description", "is_default"}),
	}).Create(&roles).Error
	if err != nil {
		dd.PrettyPrint(err)
	}

	// Revoke all users session
	// db.Exec("UPDATE users SET remember_token = NULL")
	db.Exec(`TRUNCATE bit_check_caches RESTART IDENTITY CASCADE`)
	logger.Info("Roles seeded successfully", "count", len(roles))
}
